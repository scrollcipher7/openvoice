type LanguageContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (text: string) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

function subscribeToLanguageChange(callback: () => void) {
  window.addEventListener("storage", callback);
  window.addEventListener("openvoice-language-change", callback);
  return () => {
    window.removeEventListener("storage", callback);
    window.removeEventListener("openvoice-language-change", callback);
  };
}

function getLanguageSnapshot(): Language {
  return window.localStorage.getItem("openvoice-language") === "es" ? "es" : "en";
}

function getServerLanguageSnapshot(): Language {
  return "en";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const language = useSyncExternalStore(
    subscribeToLanguageChange,
    getLanguageSnapshot,
    getServerLanguageSnapshot
  );

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = useCallback((next: Language) => {
    window.localStorage.setItem("openvoice-language", next);
    window.dispatchEvent(new Event("openvoice-language-change"));
  }, []);

  const t = useCallback((text: string) => {
    if (language !== "es") return text;
    const savedPhoto = text.match(/^Photo \d saved\. You can replace or remove it any time\.$/);
    if (savedPhoto) return "Foto guardada. Puedes cambiarla o eliminarla cuando quieras.";
    const removedPhoto = text.match(/^Photo \d removed\.$/);
    if (removedPhoto) return "Foto eliminada.";
    const dynamicPrefix = dynamicPrefixes.find(([prefix]) => text.startsWith(prefix));
    if (dynamicPrefix) return dynamicPrefix[1] + text.slice(dynamicPrefix[0].length);
    return translations[text] ?? text;
  }, [language]);

  return <LanguageContext.Provider value={{ language, setLanguage, t }}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider.");
  return context;
}

export function LanguageSwitch({ compact = false }: { compact?: boolean }) {
  const { language, setLanguage } = useLanguage();
  if (compact) {
    const nextLanguage = language === "es" ? "en" : "es";
    return (
      <button
        type="button"
        aria-label={language === "es" ? "Cambiar a inglés" : "Switch to Spanish"}
        onClick={() => setLanguage(nextLanguage)}
        className="rounded border border-[#444] bg-[#1c1c1c] px-2 py-2 text-xs text-white"
      >
        {nextLanguage === "es" ? "Español" : "English"}
      </button>
    );
  }
  return (
    <label className="flex items-center gap-2 text-xs text-gray-300">
      <span>{language === "es" ? "Idioma" : "Language"}</span>
      <select
        aria-label={language === "es" ? "Idioma" : "Language"}
        value={language}
        onChange={(event) => setLanguage(event.target.value as Language)}
        className="rounded border border-[#444] bg-[#1c1c1c] px-2 py-1 text-white"
      >
        <option value="en">English</option>
        <option value="es">Español</option>
      </select>
    </label>
  );
}
